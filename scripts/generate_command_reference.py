def _load_json(path: Path, key: str) -> dict[str, Any]:
    with path.open(encoding="utf-8") as handle:
        doc = json.load(handle)
    if not isinstance(doc, dict) or set(doc) != {key} or not isinstance(doc[key], dict):
        raise GenerationError(f"{path.name} must be an object with a single {key!r} object")
    section: dict[str, Any] = doc[key]
    return section


def build() -> dict[Path, str]:
    contracts, exit_codes = discover()
    examples = _load_json(EXAMPLES_PATH, "commands")
    fixes = _load_json(FIXES_PATH, "codes")
    problems = validate_examples(contracts, examples) + validate_fixes(contracts, fixes)
    if problems:
        raise GenerationError("\n".join(problems))
    return {
        COMMANDS_MD: render_commands(contracts, exit_codes, examples),
        ERRORS_MD: render_errors(contracts, exit_codes, fixes),
    }


def _normalized(path: Path) -> str | None:
    if not path.exists():
        return None
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def check(outputs: dict[Path, str]) -> list[str]:
    """Return a diff for each output file whose committed content differs."""
    diffs = []
    for path, expected in outputs.items():
        current = _normalized(path)
        if current == expected:
            continue
        rel = path.relative_to(ROOT).as_posix()
        lines = difflib.unified_diff(
            (current or "").splitlines(keepends=True),
            expected.splitlines(keepends=True),
            f"{rel} (committed)",
            f"{rel} (generated)",
        )
        diffs.append("".join(list(lines)[:200]) or f"{rel} is missing\n")
    return diffs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the reference files")
    mode.add_argument("--check", action="store_true", help="fail if committed files drift")
    args = parser.parse_args(argv)
    try:
        outputs = build()
    except GenerationError as exc:
        sys.stderr.write(f"reference generation failed:\n{exc}\n")
        return 2
    if args.check:
        diffs = check(outputs)
        if diffs:
            sys.stderr.write("".join(diffs))
            sys.stderr.write(
                "The command reference is stale. Run "
                "`python scripts/generate_command_reference.py --write` and commit the result.\n"
            )
            return 1
        sys.stdout.write("command reference is up to date\n")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        sys.stdout.write(f"wrote {path.relative_to(ROOT).as_posix()}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
