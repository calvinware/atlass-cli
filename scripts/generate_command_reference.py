"""Generate the command and error reference from offline `yojo` discovery.

The command set and every contract come from `yojo commands` and `yojo schema '<path>'`, run as
subprocesses of the current interpreter. No config, network, keyring, or service is used.
Curated examples in docs/examples/ are validated against the published schemas and the real
argument parser before anything is rendered.

    python scripts/generate_command_reference.py --write   # regenerate docs/reference/*.md
    python scripts/generate_command_reference.py --check   # exit 1 if the committed files drift
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import shlex
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator

from yojo.cli import NO_SERVICE_OPTIONS, build_parser
from yojo.contracts import COMMANDS_BY_PATH, ERROR_CODES, EXIT_CODES_DOC, GLOBAL_OPTIONS

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES_PATH = ROOT / "docs" / "examples" / "commands.json"
FIXES_PATH = ROOT / "docs" / "examples" / "error-fixes.json"
COMMANDS_MD = ROOT / "docs" / "reference" / "commands.md"
ERRORS_MD = ROOT / "docs" / "reference" / "errors.md"

GENERATED_NOTICE = (
    "<!-- Generated by scripts/generate_command_reference.py from `yojo commands`, `yojo schema`, "
    "and docs/examples/. Do not edit by hand. -->"
)
EXAMPLE_KEYS = frozenset(
    {"argv", "arguments", "input", "stdin", "note", "success", "error", "error_scenario"}
)
FIX_KEYS = frozenset({"meaning", "fix", "details"})
# The schema calls the `schema` command's positional `command`; argparse stores it as `path`.
ARGUMENT_DEST_ALIASES = {"command": "path"}
# Success `data` fields that echo a parsed CLI argument, keyed by argparse dest.
ECHOED_ARGUMENTS = {
    "key": "key",
    "id": "id",
    "to": "to",
    "jql": "jql",
    "cql": "cql",
    "start": "start",
    "limit": "limit",
    "path": "command",
}
# Options every command accepts; documented once, not per command.
GLOBAL_DESTS = ("config", "help", "base_url", "json")
PASSING_CHECK = ("pass", "not_applicable")
URL_RE = re.compile(r"https?://([^/\s\"'`]+)")
SECRET_MARKERS = ("Bearer ", "Basic ", "Authorization")
SAFE_HOST_SUFFIX = ".example.test"
SUBPROCESS_TIMEOUT = 60
PLURALS = {"string": "strings", "object": "objects", "integer": "integers"}


class GenerationError(Exception):
    """Discovery or example validation failed; the message lists every problem."""


@dataclass(frozen=True)
class Contract:
    path: str
    summary: str
    schema: dict[str, Any]


# --------------------------------------------------------------------------- discovery


def run_yojo(*args: str) -> Any:
    """Run `yojo` offline (stdout is a pipe, so JSON) and return `data` from its envelope."""
    command = [sys.executable, "-m", "yojo", *args]
    proc = subprocess.run(  # noqa: S603 - fixed argv: this interpreter plus registry paths
        command,
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=SUBPROCESS_TIMEOUT,
        check=False,
    )
    lines = proc.stdout.splitlines()
    if len(lines) != 1:
        raise GenerationError(f"`yojo {shlex.join(args)}` printed {len(lines)} stdout lines, not 1")
    envelope = json.loads(lines[0])
    if not isinstance(envelope, dict) or envelope.get("ok") is not True or proc.returncode != 0:
        raise GenerationError(f"`yojo {shlex.join(args)}` failed: {lines[0][:500]}")
    return envelope["data"]


def discover() -> tuple[list[Contract], dict[str, str]]:
    listing = run_yojo("commands")
    paths = [entry["path"] for entry in listing["commands"]]
    duplicates = sorted({p for p in paths if paths.count(p) > 1})
    if duplicates:
        raise GenerationError(f"`yojo commands` lists duplicate paths: {duplicates}")
    if set(paths) != set(COMMANDS_BY_PATH):
        raise GenerationError(
            "`yojo commands` does not match COMMANDS_BY_PATH: "
            f"missing {sorted(set(COMMANDS_BY_PATH) - set(paths))}, "
            f"extra {sorted(set(paths) - set(COMMANDS_BY_PATH))}"
        )
    if listing["exit_codes"] != EXIT_CODES_DOC:
        raise GenerationError("`yojo commands` exit_codes differ from EXIT_CODES_DOC")
    contracts = []
    for path in paths:
        schema = run_yojo("schema", path)
        if schema.get("command") != path:
            raise GenerationError(f"`yojo schema '{path}'` returned {schema.get('command')!r}")
        contracts.append(Contract(path=path, summary=schema["summary"], schema=schema))
    return contracts, listing["exit_codes"]


# --------------------------------------------------------------------------- parser introspection


def leaf_parsers(
    parser: argparse.ArgumentParser, prefix: tuple[str, ...] = ()
) -> dict[str, argparse.ArgumentParser]:
    found: dict[str, argparse.ArgumentParser] = {}
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, sub in action.choices.items():
                found.update(leaf_parsers(sub, (*prefix, name)))
            return found
    return {" ".join(prefix): parser}


def _cli_actions(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in parser._actions if a.dest not in GLOBAL_DESTS]


def _metavar(action: argparse.Action) -> str:
    metavar = action.metavar if isinstance(action.metavar, str) else None
    return metavar or action.dest.upper()


def cli_form(action: argparse.Action) -> str:
    if not action.option_strings:
        name = _metavar(action)
        return f"{name}..." if action.nargs == "+" else name
    flag = action.option_strings[0]
    if action.nargs == 0:
        return flag
    form = f"{flag} {_metavar(action)}"
    return f"{form}..." if isinstance(action, argparse._AppendAction) else form


def synopsis(path: str, parser: argparse.ArgumentParser) -> str:
    grouped = {id(a): g for g in parser._mutually_exclusive_groups for a in g._group_actions}
    parts = [f"yojo {path}"]
    seen_groups: set[int] = set()
    for action in _cli_actions(parser):
        group = grouped.get(id(action))
        if group is not None:
            if id(group) in seen_groups:
                continue
            seen_groups.add(id(group))
            inner = " | ".join(cli_form(a) for a in group._group_actions)
            parts.append(f"({inner})" if group.required else f"[{inner}]")
        elif not action.required and (action.option_strings or action.nargs == "?"):
            parts.append(f"[{cli_form(action)}]")
        else:
            parts.append(cli_form(action))
    if path not in NO_SERVICE_OPTIONS:
        parts.append("[--config PATH] [--base-url URL]")
    parts.append("[--json]")
    return " ".join(parts)


# --------------------------------------------------------------------------- validation


def _strings(value: Any) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, dict):
        return [s for k, v in value.items() for s in (*_strings(k), *_strings(v))]
    if isinstance(value, list):
        return [s for item in value for s in _strings(item)]
    return []


def _schema_errors(schema: dict[str, Any], instance: Any, where: str) -> list[str]:
    return [
        f"{where}: {error.message} at /{'/'.join(str(p) for p in error.absolute_path)}"
        for error in Draft202012Validator(schema).iter_errors(instance)
    ]


def validate_examples(contracts: list[Contract], examples: dict[str, Any]) -> list[str]:
    problems: list[str] = []
    paths = [c.path for c in contracts]
    missing = sorted(set(paths) - set(examples))
    extra = sorted(set(examples) - set(paths))
    if missing:
        problems.append(f"commands.json has no example for: {missing}")
    if extra:
        problems.append(f"commands.json has examples for unknown commands: {extra}")
    parser = build_parser()
    leaves = leaf_parsers(parser)
    for contract in contracts:
        example = examples.get(contract.path)
        if not isinstance(example, dict):
            continue
        where = f"commands.json[{contract.path!r}]"
        schema = contract.schema
        unknown = sorted(set(example) - EXAMPLE_KEYS)
        if unknown:
            problems.append(f"{where}: unknown keys {unknown}")
        absent = sorted({"argv", "arguments", "input", "success", "error"} - set(example))
        if absent:
            problems.append(f"{where}: missing keys {absent}")
            continue
        argv = example["argv"]
        parsed: argparse.Namespace | None = None
        try:
            parsed = parser.parse_args(argv)
        except Exception as exc:  # noqa: BLE001 - report any parser rejection as a problem
            problems.append(f"{where}: argv does not parse: {exc}")
        else:
            if parsed.command != contract.path:
                problems.append(f"{where}: argv parses as {parsed.command!r}")
                parsed = None
        problems += _schema_errors(schema["arguments"], example["arguments"], f"{where}.arguments")
        leaf = leaves.get(contract.path)
        if parsed is not None and leaf is not None:
            problems += _argv_mismatches(contract, leaf, parsed, example["arguments"], where)
        problems += _argument_mapping(contract, leaves.get(contract.path), where)
        input_action = (
            next((a for a in _cli_actions(leaf) if a.dest == "input"), None) if leaf else None
        )
        if schema["input"] is None:
            if example["input"] is not None:
                problems.append(f"{where}: input must be null; the command takes no JSON input")
        elif example["input"] is None:
            if input_action is not None and input_action.required:
                problems.append(f"{where}: input is required by the schema")
            if "--input" in argv:
                problems.append(f"{where}: argv uses --input but the example shows no input")
        else:
            problems += _schema_errors(schema["input"], example["input"], f"{where}.input")
            if argv[-2:] != ["--input", "-"]:
                problems.append(f"{where}: argv must end with --input - to show stdin input")
        if "stdin" in example and not isinstance(example["stdin"], str):
            problems.append(f"{where}: stdin must be text")
        problems += _schema_errors(schema["success"], example["success"], f"{where}.success")
        problems += _schema_errors(schema["error"], example["error"], f"{where}.error")
        code = example["error"].get("error", {}).get("code")
        if code not in schema["error_codes"]:
            problems.append(f"{where}: error code {code!r} is not in this command's error_codes")
        if not isinstance(example.get("error_scenario"), str) or not example["error_scenario"]:
            problems.append(f"{where}: error_scenario must describe the failing call")
        if parsed is not None:
            problems += semantic_problems(parsed, example, where)
        for text in _strings(example):
            for host in URL_RE.findall(text):
                if not host.endswith(SAFE_HOST_SUFFIX):
                    problems.append(f"{where}: URL host {host!r} is not a *{SAFE_HOST_SUFFIX} host")
            if any(marker in text for marker in SECRET_MARKERS):
                problems.append(f"{where}: example text looks like a credential header")
    return problems


def _parsed_value(parsed: argparse.Namespace, dest: str) -> Any:
    value = getattr(parsed, dest, None)
    # The nargs="+" `schema` command path is one space-joined argument; --set stays a list.
    return " ".join(value) if dest == "path" and isinstance(value, list) else value


def _argv_mismatches(
    contract: Contract,
    parser: argparse.ArgumentParser,
    parsed: argparse.Namespace,
    arguments: Any,
    where: str,
) -> list[str]:
    """Each documented argument must equal what argparse produces from argv, after type
    conversion; an argument left out of `arguments` must be left at its parser default."""
    if not isinstance(arguments, dict):
        return []
    actions = {a.dest: a for a in _cli_actions(parser)}
    problems = []
    for name in contract.schema["arguments"].get("properties", {}):
        dest = ARGUMENT_DEST_ALIASES.get(name, name)
        if dest not in actions:
            continue
        actual = _parsed_value(parsed, dest)
        expected = arguments[name] if name in arguments else actions[dest].default
        if actual != expected:
            problems.append(f"{where}: argv gives {name}={actual!r} but arguments has {expected!r}")
    return problems


def _failing(checks: Any) -> list[Any]:
    if not isinstance(checks, list):
        return []
    return [c for c in checks if isinstance(c, dict) and c.get("status") not in PASSING_CHECK]


def _checklist_problems(checklist: Any, label: str) -> list[str]:
    if not isinstance(checklist, dict) or "ready" not in checklist:
        return []
    problems = []
    ready = checklist.get("transition") is not None and not _failing(checklist.get("checks"))
    if checklist["ready"] != ready:
        problems.append(f"{label}: ready is {checklist['ready']!r} but its checks imply {ready!r}")
    transition = checklist.get("transition")
    operations = (checklist.get("plan") or {}).get("operations") or []
    if (
        isinstance(transition, dict)
        and operations
        and operations[-1].get("transition_id") != transition.get("id")
    ):
        problems.append(f"{label}: the planned transition_id differs from transition.id")
    return problems


def _retry_problems(error: dict[str, Any], details: dict[str, Any], where: str) -> list[str]:
    """A refusal offers a shell-quoted retry matching its argv; an uncertain write offers none."""
    code = error.get("code")
    if code in ("outcome_unknown", "partial_transition"):
        if "retry" in details or "retry_argv" in details:
            return [f"{where}: {code} must not offer a retry"]
        return []
    if code != "requirements_unmet":
        return []
    problems = []
    if details.get("nothing_sent") is not True:
        problems.append(f"{where}: requirements_unmet must say nothing_sent: true")
    argv = details.get("retry_argv")
    if argv is not None:
        if not isinstance(argv, list) or argv[:1] != ["yojo"]:
            problems.append(f"{where}: retry_argv must start with yojo")
        elif details.get("retry") != shlex.join(argv):
            problems.append(f"{where}: retry is not the shell-quoted retry_argv")
    return problems


def semantic_problems(parsed: argparse.Namespace, example: dict[str, Any], where: str) -> list[str]:
    """Shown results must agree with the call that produced them.

    Schema validation alone accepts a success for a different key, destination, query, or
    version; these rules catch that.
    """
    problems: list[str] = []
    success = example.get("success")
    data = success.get("data") if isinstance(success, dict) else None
    error_body = example.get("error")
    error = error_body.get("error") if isinstance(error_body, dict) else None
    if not isinstance(data, dict) or not isinstance(error, dict):
        return problems
    raw_details = error.get("details")
    details: dict[str, Any] = raw_details if isinstance(raw_details, dict) else {}
    payload = example["input"] if isinstance(example.get("input"), dict) else {}

    def expect(label: str, actual: Any, expected: Any) -> None:
        if actual != expected:
            problems.append(f"{where}: {label} is {actual!r} but the call implies {expected!r}")

    for dest, field in ECHOED_ARGUMENTS.items():
        if field in data and hasattr(parsed, dest):
            expect(f"success.data.{field}", data[field], _parsed_value(parsed, dest))
    for field in ("project", "space_key", "title"):
        if field in payload and field in data:
            expect(f"success.data.{field}", data[field], payload[field])
    url, key = data.get("url"), data.get("key")
    if (
        isinstance(url, str)
        and isinstance(key, str)
        and url.split("?", 1)[0].rpartition("/browse/")[2] != key
    ):
        problems.append(f"{where}: success.data.url does not point at {key}")
    file_arg = getattr(parsed, "file", None)
    if isinstance(file_arg, str) and isinstance(data.get("attachments"), list):
        names = [a.get("filename") for a in data["attachments"] if isinstance(a, dict)]
        expect("success.data.attachments filenames", names, [Path(file_arg).name])

    expected_version = payload.get("expected_version")
    if isinstance(expected_version, int):
        expect("success.data.previous_version", data.get("previous_version"), expected_version)
        expect("success.data.version", data.get("version"), expected_version + 1)
        if error.get("code") == "version_conflict":
            expect(
                "error.details.expected_version", details.get("expected_version"), expected_version
            )
            current = details.get("current_version")
            if not isinstance(current, int) or current == expected_version:
                problems.append(f"{where}: version_conflict needs a different current_version")

    if "ready" in data:
        problems += _checklist_problems(data, f"{where}: success.data")
    elif _failing(data.get("checks")):
        problems.append(f"{where}: success.data.checks has a failing check")
    if data.get("status") == "pass" and "summary" in data:
        expect("success.data.summary", data["summary"], {"pass": len(data.get("checks", []))})
    operations = data.get("operations")
    if isinstance(operations, list) and operations:
        if any(op.get("status") != "succeeded" for op in operations if isinstance(op, dict)):
            problems.append(f"{where}: a successful write must show every operation succeeded")
        if "transition_id" in data:
            expect(
                "success.data.transition_id",
                data["transition_id"],
                operations[-1].get("transition_id"),
            )

    if error.get("code") == "requirements_unmet" and not _failing(details.get("checks")):
        problems.append(f"{where}: requirements_unmet must show at least one failing check")
    problems += _retry_problems(error, details, where)
    return problems


def _argument_mapping(
    contract: Contract, parser: argparse.ArgumentParser | None, where: str
) -> list[str]:
    if parser is None:
        return [f"{where}: no argparse leaf for this command"]
    dests = {a.dest for a in _cli_actions(parser)}
    names = set(contract.schema["arguments"].get("properties", {}))
    mapped = {ARGUMENT_DEST_ALIASES.get(n, n) for n in names}
    problems = []
    if mapped - dests:
        problems.append(f"{where}: schema arguments without a CLI option: {sorted(mapped - dests)}")
    if dests - mapped:
        problems.append(f"{where}: CLI options missing from the schema: {sorted(dests - mapped)}")
    return problems


def validate_fixes(contracts: list[Contract], fixes: dict[str, Any]) -> list[str]:
    problems: list[str] = []
    missing = sorted(set(ERROR_CODES) - set(fixes))
    extra = sorted(set(fixes) - set(ERROR_CODES))
    if missing:
        problems.append(f"error-fixes.json has no entry for: {missing}")
    if extra:
        problems.append(f"error-fixes.json has entries for unknown codes: {extra}")
    for code, entry in fixes.items():
        where = f"error-fixes.json[{code!r}]"
        if not isinstance(entry, dict):
            problems.append(f"{where}: must be an object")
            continue
        if set(entry) - FIX_KEYS or not {"meaning", "fix"} <= set(entry):
            problems.append(f"{where}: keys must be meaning, fix, and optional details")
        for key, value in entry.items():
            if not isinstance(value, str) or not value.strip():
                problems.append(f"{where}.{key}: must be non-empty text")
    published = {c for contract in contracts for c in contract.schema["error_codes"]}
    if published - set(ERROR_CODES):
        problems.append(f"schemas list unregistered codes: {sorted(published - set(ERROR_CODES))}")
    for contract in contracts:
        enum = contract.schema["error"]["properties"]["error"]["properties"]["code"]["enum"]
        if set(enum) != set(ERROR_CODES):
            problems.append(f"{contract.path}: error envelope enum differs from ERROR_CODES")
    return problems


# --------------------------------------------------------------------------- rendering helpers


def _code(value: Any) -> str:
    text = value if isinstance(value, str) else json.dumps(value)
    return f"`{text}`"


def type_label(schema: dict[str, Any]) -> str:
    if "const" in schema:
        return f"constant {_code(schema['const'])}"
    if "enum" in schema:
        return "one of " + ", ".join(_code(v) for v in schema["enum"])
    if "oneOf" in schema:
        return " or ".join(type_label(s) for s in schema["oneOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind == "array":
        items = schema.get("items")
        if not isinstance(items, dict):
            return "array"
        label = type_label(items)
        return f"array of {PLURALS.get(label, label)}"
    if kind == "object":
        values = schema.get("additionalProperties")
        if isinstance(values, dict) and values:
            return f"object (field name to {type_label(values)})"
        return "object"
    return str(kind) if kind else "any"


def constraints(schema: dict[str, Any]) -> str:
    notes = []
    for key, label in (
        ("minLength", "min length"),
        ("maxLength", "max length"),
        ("minimum", "min"),
        ("maximum", "max"),
        ("maxItems", "max items"),
    ):
        if key in schema:
            notes.append(f"{label} {schema[key]}")
    if "pattern" in schema:
        notes.append(f"pattern `{schema['pattern']}`")
    if "default" in schema:
        notes.append(f"default {_code(schema['default'])}")
    return "; ".join(notes)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ") or " "


def property_rows(schema: dict[str, Any], prefix: str = "") -> list[tuple[str, str, bool, str]]:
    rows = []
    required = set(schema.get("required", []))
    for name, prop in schema.get("properties", {}).items():
        notes = "; ".join(n for n in (constraints(prop), prop.get("description", "")) if n)
        rows.append((f"{prefix}{name}", type_label(prop), name in required, notes))
        if prop.get("type") == "object" and prop.get("properties"):
            rows += property_rows(prop, f"{prefix}{name}.")
    return rows


def alternatives(schema: dict[str, Any]) -> list[str]:
    notes = []
    for key, label in (("oneOf", "exactly one of"), ("anyOf", "at least one of")):
        options = schema.get(key)
        if isinstance(options, list) and all(set(o) == {"required"} for o in options):
            names = ", ".join(f"`{n}`" for o in options for n in o["required"])
            notes.append(f"Requires {label} {names}.")
    return notes


def _json_block(value: Any) -> list[str]:
    return ["```json", json.dumps(value, indent=2, ensure_ascii=False), "```"]


def invocation(example: dict[str, Any]) -> list[str]:
    command = "yojo " + shlex.join(example["argv"])
    if example["input"] is not None:
        body = json.dumps(example["input"], indent=2, ensure_ascii=False)
        return ["```bash", f"{command} <<'JSON'", body, "JSON", "```"]
    if "stdin" in example:
        return ["```bash", f"{command} <<'EOF'", example["stdin"].rstrip("\n"), "EOF", "```"]
    return ["```bash", command, "```"]


def anchor(text: str) -> str:
    return re.sub(r"[^a-z0-9_ -]", "", text.lower()).replace(" ", "-")


# --------------------------------------------------------------------------- pages


def render_commands(
    contracts: list[Contract], exit_codes: dict[str, str], examples: dict[str, Any]
) -> str:
    leaves = leaf_parsers(build_parser())
    out = [
        GENERATED_NOTICE,
        "",
        "# Command reference",
        "",
        f"`yojo` has **{len(contracts)} commands**. This page is generated from `yojo commands`, "
        "`yojo schema '<command>'`, and the checked examples in "
        "[`docs/examples/commands.json`](../examples/commands.json). The JSON Schemas remain the "
        "source of truth; run `yojo schema '<command>'` for the exact contract.",
        "",
        "> [!NOTE]",
        "> Examples use synthetic data (`EXAMPLE-*` keys, `*.example.test` hosts) and were "
        "captured from real runs against test fixtures. They are pretty-printed here; when "
        "stdout is piped or `--json` is given, `yojo` prints each envelope on one line. On a "
        "terminal it shows a readable view of the same envelope, with the same exit code. "
        "Invocations use POSIX shell syntax.",
        "",
        "Every command accepts these options:",
        "",
        "| Option | Meaning |",
        "|--------|---------|",
        *(f"| `{option}` | {_cell(meaning)} |" for option, meaning in GLOBAL_OPTIONS.items()),
        "",
        "Every command produces exactly one envelope and exits with one of these codes:",
        "",
        "| Exit | Meaning |",
        "|------|---------|",
        *(f"| {code} | {_cell(meaning)} |" for code, meaning in exit_codes.items()),
        "",
        "Each error code, with its meaning and fix, is in the [error catalog](errors.md).",
        "",
        "## Commands at a glance",
        "",
        "| Command | Summary | JSON input |",
        "|---------|---------|------------|",
    ]
    for contract in contracts:
        has_input = "yes" if contract.schema["input"] is not None else "no"
        out.append(
            f"| [`yojo {contract.path}`](#{anchor('yojo ' + contract.path)}) "
            f"| {_cell(contract.summary)} | {has_input} |"
        )
    for contract in contracts:
        out += ["", *_command_section(contract, leaves[contract.path], examples[contract.path])]
    return "\n".join(out) + "\n"


def _command_section(
    contract: Contract, parser: argparse.ArgumentParser, example: dict[str, Any]
) -> list[str]:
    schema = contract.schema
    actions = {a.dest: a for a in _cli_actions(parser)}
    out = [
        f"## `yojo {contract.path}`",
        "",
        contract.summary,
        "",
        "```text",
        synopsis(contract.path, parser),
        "```",
        "",
        "**Arguments**",
        "",
    ]
    rows = property_rows(schema["arguments"])
    if rows:
        out += ["| Argument | CLI | Type | Required | Notes |", "|---|---|---|---|---|"]
        for name, kind, required, notes in rows:
            action = actions[ARGUMENT_DEST_ALIASES.get(name, name)]
            out.append(
                f"| `{name}` | `{cli_form(action)}` | {_cell(kind)} | "
                f"{'yes' if required else 'no'} | {_cell(notes)} |"
            )
    else:
        out.append("None.")
    alt = alternatives(schema["arguments"])
    if alt:
        out += ["", *alt]
    out += ["", "**Input**", ""]
    if schema["input"] is None:
        out.append("No JSON input.")
    else:
        out += [
            "A JSON object from `--input PATH`, or from stdin with `--input -`. Unknown "
            "properties and duplicate keys are rejected. Where the command also has flags, the "
            "input is an alternative to them; a flag and an input property that disagree are "
            "refused.",
            "",
            "| Property | Type | Required | Notes |",
            "|---|---|---|---|",
        ]
        for name, kind, required, notes in property_rows(schema["input"]):
            out.append(
                f"| `{name}` | {_cell(kind)} | {'yes' if required else 'no'} | {_cell(notes)} |"
            )
        alt = alternatives(schema["input"])
        if alt:
            out += ["", *alt]
    data_schema = schema["success"]["properties"]["data"]
    out += ["", "**Output**", "", "Success `data` fields:", ""]
    out += ["| Field | Type | Always present |", "|---|---|---|"]
    for name, kind, required, _ in property_rows(data_schema):
        if "." in name:
            continue
        out.append(f"| `{name}` | {_cell(kind)} | {'yes' if required else 'no'} |")
    error = example["error"]["error"]
    error_exit = ERROR_CODES[error["code"]].value
    out += [
        "",
        "**Example**",
        "",
        *invocation(example),
        "",
    ]
    if "note" in example:
        out += [example["note"], ""]
    out += [
        "Success (exit 0):",
        "",
        *_json_block(example["success"]),
        "",
        f"Error: {example['error_scenario']} "
        f"([`{error['code']}`](errors.md#{error['code']}), exit {error_exit}):",
        "",
        *_json_block(example["error"]),
        "",
        "**Error codes**",
        "",
        "| Exit | Error codes |",
        "|------|-------------|",
    ]
    by_exit: dict[int, list[str]] = {}
    for code in schema["error_codes"]:
        by_exit.setdefault(ERROR_CODES[code].value, []).append(f"[`{code}`](errors.md#{code})")
    out += [f"| {exit_code} | {', '.join(codes)} |" for exit_code, codes in sorted(by_exit.items())]
    return out


def render_errors(
    contracts: list[Contract], exit_codes: dict[str, str], fixes: dict[str, Any]
) -> str:
    returned_by: dict[str, list[str]] = {code: [] for code in ERROR_CODES}
    for contract in contracts:
        for code in contract.schema["error_codes"]:
            returned_by[code].append(contract.path)
    out = [
        GENERATED_NOTICE,
        "",
        "# Error catalog",
        "",
        f"`yojo` defines **{len(ERROR_CODES)} error codes**. Every failure prints "
        '`{"ok": false, "error": {"code", "message", "fix", "details"}}` and exits with the code '
        "below. `error.fix` in the real output is specific to the failing call; follow it first. "
        "This page explains each code and the general fix.",
        "",
        "> [!IMPORTANT]",
        "> `yojo` never retries a write. A refusal (`requirements_unmet`) sent nothing; when a "
        "corrected command line would help, it carries one in `details.retry`, otherwise "
        "`retry` is `null` and each check's `fix` says what to do. After `outcome_unknown` "
        "(exit 6) or `partial_transition` (exit 7) there is no retry: inspect the issue, page, "
        "or pull request before running anything again. See "
        "[Writes and retries](../commands.md#writes-and-retries).",
        "",
        "## Exit codes",
        "",
        "| Exit | Meaning | Error codes |",
        "|------|---------|-------------|",
    ]
    for exit_code, meaning in exit_codes.items():
        codes = [c for c, e in ERROR_CODES.items() if str(e.value) == exit_code]
        listed = ", ".join(f"[`{c}`](#{c})" for c in codes) or "none (success)"
        out.append(f"| {exit_code} | {_cell(meaning)} | {listed} |")
    out += ["", "## Error codes", ""]
    for code, code_exit in ERROR_CODES.items():
        entry = fixes[code]
        commands = returned_by[code]
        others = [c.path for c in contracts if c.path not in commands]
        if not others:
            where = "every command"
        elif commands and len(others) <= 3:
            where = "every command except " + ", ".join(f"`yojo {p}`" for p in others)
        elif commands:
            where = ", ".join(f"[`yojo {p}`](commands.md#{anchor('yojo ' + p)})" for p in commands)
        else:
            where = "no command schema lists this code"
        out += [
            f"### `{code}`",
            "",
            f"**Exit {code_exit.value}.** {entry['meaning']}",
            "",
            f"**Fix:** {entry['fix']}",
            "",
        ]
        if "details" in entry:
            out += [f"**Details:** {entry['details']}", ""]
        out += [f"**Returned by:** {where}.", ""]
    return "\n".join(out).rstrip("\n") + "\n"


